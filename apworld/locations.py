class RWBYLocation(Location):
    game = "RWBY Grimm Eclipse"

def get_location_names_with_ids(location_names: list[str]) -> dict[str, int | None]:
    return {location_name: LOCATION_NAME_TO_ID[location_name] for location_name in location_names}

def create_all_locations(world: RWBYWorld) -> None:
    for level, checks in {
        "Boots on the Ground": ch1,
        "Technical Difficulties": ch2,
        "The Collapse": ch3,
        "Below the Surface": ch4,
        "Right on Track": ch5,
        "End of the Line": ch6,
        "The Island of Dr. Merlot": ch7,
        "A Grimm Discovery": ch8,
        "The Grand Tour": ch9,
        "Final Exam": ch10,
    }.items():
        world.get_region(level).add_locations(checks, RWBYLocation)

    characters = ["Ruby", "Weiss", "Blake", "Yang"]
    if world.options.jnpr_enabled:
        characters += ["Jaune", "Nora", "Pyrrha", "Ren"]

    for character in characters:
        names = [f"{character} - Level {i}" for i in range(2, world.options.character_level_checks + 1)]
        world.get_region(f"{character} Level Up").add_locations(get_location_names_with_ids(names), RWBYLocation)
